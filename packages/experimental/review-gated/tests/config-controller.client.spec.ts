/** RG draft edits are atomic, revision-fenced, and isolated from Session policy. */
import { describe, expect, it, onTestFinished } from 'vitest'
import type { RgSettings } from '../src/types.ts'
import { modelKey } from '../src/client/model-pools.ts'
import { catalog, fixture, main, settings, waitForState, worker } from './fixture.client.ts'

describe('RG configuration drafts', () => {
  it('loads the model directory only when the settings source is observed', async () => {
    const f = fixture({ subscribe: false })
    expect(f.readCatalog).not.toHaveBeenCalled()
    f.open()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    expect(f.readCatalog).toHaveBeenCalledOnce()
    expect(f.read().dirty).toBe(false)
  })

  it('atomically saves all roles and limits under the original revision', async () => {
    const f = fixture()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    f.face.toggleModel('main', modelKey(worker))
    f.face.selectDefault('main', modelKey(worker))
    f.face.setReviewerMode('custom')
    f.face.selectEffort('reviewer', modelKey(main), 'low')
    f.face.editLimit('maxReviewAttempts', '3')
    f.face.save()
    await waitForState(f.face, state => !state.saving)
    expect(f.mutate).toHaveBeenCalledOnce()
    expect(f.mutate.mock.calls[0]?.[1]).toBe(1)
    expect(f.current().value?.settings).toMatchObject({ main: { default: worker }, maxReviewAttempts: 3,
      reviewer: { mode: 'custom', pool: { candidates: [{ ...main, reasoningEffort: 'low' }, worker] } } })
    expect(f.read().savedNotice).not.toBeNull()
    expect(f.read().dirty).toBe(false)
  })

  it('requires a replacement default after removing a default candidate', async () => {
    const f = fixture()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    f.face.toggleModel('main', modelKey(worker))
    f.face.toggleModel('main', modelKey(main))
    expect(f.read().errors.main).toBe('defaultRequired')
    f.face.save()
    expect(f.mutate).not.toHaveBeenCalled()
    f.face.selectDefault('main', modelKey(worker))
    expect(f.read().errors.main).toBeNull()
    f.face.toggleModel('worker', modelKey(worker))
    expect(f.read().errors.worker).toBe('poolRequired')
  })

  it('keeps hidden custom reviewer edits local and excludes them from an inherited save', async () => {
    const f = fixture()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    f.face.setReviewerMode('custom')
    f.face.selectEffort('reviewer', modelKey(main), 'low')
    f.face.setReviewerMode('inherit-main')
    f.face.setReviewerMode('custom')
    expect(f.read().settings?.reviewer).toMatchObject({ pool: { candidates: [{ reasoningEffort: 'low' }] } })
    f.face.setReviewerMode('inherit-main')
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    await waitForState(f.face, state => !state.saving)
    expect(f.current().value?.settings.reviewer).toEqual({ mode: 'inherit-main' })
  })

  it('blocks invalid whole-number budgets and restores values on discard', () => {
    const f = fixture()
    f.face.editLimit('maxWorkerAttempts', '')
    f.face.editLimit('maxScopeFiles', '1.5')
    expect(f.read().invalidLimits).toEqual(['maxWorkerAttempts', 'maxScopeFiles'])
    f.face.save()
    expect(f.mutate).not.toHaveBeenCalled()
    f.face.discard()
    expect(f.read().limits.maxWorkerAttempts).toBe('2')
    expect(f.read().dirty).toBe(false)
  })

  it('does not edit or save a read-only Host document', () => {
    const f = fixture({ writable: false })
    f.face.editLimit('maxReviewAttempts', '9')
    f.face.toggleModel('main', modelKey(worker))
    f.face.save()
    expect(f.read()).toMatchObject({ dirty: false, invalid: true })
    expect(f.mutate).not.toHaveBeenCalled()
  })

  it('retains stored unavailable models without changing their default', async () => {
    const f = fixture({ readCatalog: async () => ({ ...catalog, groups: [] }) })
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    expect(f.read().rows.main).toMatchObject([{ available: false, selected: true, isDefault: true }])
    f.face.toggleModel('main', modelKey(main))
    expect(f.read().rows.main[0]?.selected).toBe(false)
    f.face.toggleModel('main', modelKey(main))
    expect(f.read().rows.main[0]?.selected).toBe(false)
    expect(f.read().settings?.main.default).toBeNull()
  })

  it('shows partial provider failure and retains rows when a later directory read fails', async () => {
    const f = fixture({ readCatalog: async () => ({ ...catalog, failures: [{ id: 'beta', name: 'Beta', message: 'unavailable' }] }) })
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    expect(f.read().partialCatalog).toBe(true)
    f.readCatalog.mockRejectedValueOnce(new Error('network'))
    f.face.retryCatalog()
    await waitForState(f.face, state => state.catalogStatus === 'error')
    expect(f.read().rows.main.some(row => row.available && row.model === 'smart')).toBe(true)
  })

  it('rejects stale drafts rather than overwriting another browser', () => {
    const f = fixture()
    f.face.editLimit('maxWorkerAttempts', '3')
    f.update({ ...settings(), maxReviewAttempts: 8 })
    expect(f.read().conflicted).toBe(true)
    f.face.save()
    expect(f.mutate).not.toHaveBeenCalled()
    f.face.discard()
    expect(f.read().limits.maxReviewAttempts).toBe('8')
  })

  it('retains a draft and reports uncertainty after a lost save response', async () => {
    const f = fixture()
    f.mutate.mockRejectedValueOnce(new Error('connection lost'))
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    await waitForState(f.face, state => !state.saving)
    expect(f.read()).toMatchObject({ failed: true, uncertain: true, dirty: true, savedNotice: null })
    expect(f.read().limits.maxWorkerAttempts).toBe('3')
  })

  it('confirms a lost response only when the Host mirror contains the submitted document', async () => {
    const f = fixture()
    f.mutate.mockImplementationOnce(async (ops) => {
      const op = ops[0]
      if (op?.op === 'set') f.update(op.value as RgSettings)
      throw new Error('lost response after commit')
    })
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    await waitForState(f.face, state => !state.saving)
    expect(f.read()).toMatchObject({ failed: false, uncertain: false, dirty: false })
    expect(f.read().savedNotice).not.toBeNull()
  })

  it('admits only one save while an earlier save is pending', async () => {
    const f = fixture()
    const gate = Promise.withResolvers<boolean>()
    onTestFinished(() => { gate.resolve(false) })
    f.mutate.mockReturnValueOnce(gate.promise)
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    f.face.save()
    expect(f.mutate).toHaveBeenCalledOnce()
    gate.resolve(false)
    await waitForState(f.face, state => !state.saving)
    expect(f.read().failed).toBe(true)
  })

  it('drops page drafts and ignores old write settlements after reconnecting', async () => {
    const f = fixture()
    const gate = Promise.withResolvers<boolean>()
    onTestFinished(() => { gate.resolve(false) })
    f.mutate.mockReturnValueOnce(gate.promise)
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    f.controller.resetConnection()
    expect(f.read()).toMatchObject({ dirty: false, saving: false, savedNotice: null })
    gate.resolve(true)
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    expect(f.read().savedNotice).toBeNull()
    f.face.editLimit('maxWorkerAttempts', '4')
    f.close()
    expect(f.read().dirty).toBe(true)
    f.open()
    expect(f.read().limits.maxWorkerAttempts).toBe('4')
  })

  it.each(['reset', 'unavailable'] as const)('retains unknown write outcome on %s without carrying a draft', async (transition) => {
    const f = fixture()
    const gate = Promise.withResolvers<boolean>()
    onTestFinished(() => { gate.resolve(false) })
    f.mutate.mockReturnValueOnce(gate.promise)
    f.face.editLimit('maxWorkerAttempts', '9')
    f.face.save()
    if (transition === 'reset') f.controller.resetConnection()
    else f.publish({ status: 'unavailable', value: undefined, revision: undefined, writable: false })
    expect(f.read()).toMatchObject({ uncertain: true, dirty: false, saving: false })
    if (transition === 'unavailable') {
      f.face.acknowledgeUncertain()
      expect(f.read().uncertain).toBe(true)
    }
    f.publish({ status: 'ready', value: { settings: { ...settings(), maxWorkerAttempts: 5 } }, revision: 8, writable: true })
    expect(f.read()).toMatchObject({ uncertain: true, dirty: false, savedNotice: null })
    expect(f.read().limits.maxWorkerAttempts).toBe('5')
    gate.resolve(true)
    await gate.promise
    expect(f.read()).toMatchObject({ uncertain: true, savedNotice: null })
    f.face.discard()
    expect(f.read().uncertain).toBe(true)
    f.face.acknowledgeUncertain()
    expect(f.read().uncertain).toBe(false)
  })

  it('keeps an unconfigured Host value unchanged until an explicit valid save', async () => {
    const f = fixture({ value: { ...settings(), configured: false } })
    expect(f.read().settings?.configured).toBe(false)
    f.face.save()
    expect(f.mutate).not.toHaveBeenCalled()
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    await waitForState(f.face, state => !state.saving)
    expect(f.current().value?.settings.configured).toBe(true)
  })

  it('blocks a newly selected route that disappears while retaining saved missing routes', async () => {
    const f = fixture()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    f.face.toggleModel('main', modelKey(worker))
    f.readCatalog.mockResolvedValueOnce({ ...catalog, groups: [] })
    f.controller.refreshCatalog()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    expect(f.read().errors.main).toBe('candidateUnavailable')
    f.face.save()
    expect(f.mutate).not.toHaveBeenCalled()
    f.face.toggleModel('main', modelKey(worker))
    f.face.editLimit('maxWorkerAttempts', '3')
    expect(f.read().errors.main).toBeNull()
    f.face.save()
    await waitForState(f.face, state => !state.saving)
    expect(f.current().value?.settings.main).toEqual(settings().main)
  })

  it('requires an advertised effort after the directory drops the saved effort', async () => {
    const f = fixture({ readCatalog: async () => ({ ...catalog, groups: [{ id: 'alpha', name: 'Alpha', models: [
      { id: 'smart', name: 'Smart', reasoning: { efforts: [{ id: 'low', name: 'Low' }] } }, { id: 'fast', name: 'Fast' },
    ] }] }) })
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    expect(f.read().errors.main).toBe('effortInvalid')
    f.face.selectEffort('main', modelKey(main), 'unsupported')
    expect(f.read().errors.main).toBe('effortInvalid')
    f.face.selectEffort('main', modelKey(main), undefined)
    expect(f.read().errors.main).toBeNull()
  })

  it('preserves the original revision when the Host refuses a racing save', async () => {
    const f = fixture()
    const gate = Promise.withResolvers<boolean>()
    onTestFinished(() => { gate.resolve(false) })
    f.mutate.mockReturnValueOnce(gate.promise)
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    f.update({ ...settings(), maxReviewAttempts: 9 })
    gate.resolve(false)
    await waitForState(f.face, state => !state.saving)
    expect(f.read()).toMatchObject({ failed: true, conflicted: true, dirty: true })
    expect(f.read().limits.maxReviewAttempts).toBe('2')
    f.face.save()
    expect(f.mutate).toHaveBeenCalledOnce()
    f.face.discard()
    expect(f.read().limits.maxReviewAttempts).toBe('9')
  })

  it('drops drafts and save notices when the Host withdraws its settings namespace', async () => {
    const f = fixture()
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    await waitForState(f.face, state => !state.saving)
    expect(f.read().savedNotice).not.toBeNull()
    f.publish({ status: 'unavailable' })
    expect(f.read()).toMatchObject({ available: false, dirty: false, savedNotice: null })
  })

  it('blocks edits after writability changes and keeps the visible draft until discard', () => {
    const f = fixture()
    f.face.editLimit('maxWorkerAttempts', '3')
    f.publish({ writable: false })
    f.face.editLimit('maxWorkerAttempts', '4')
    f.face.save()
    expect(f.mutate).not.toHaveBeenCalled()
    expect(f.read().limits.maxWorkerAttempts).toBe('3')
    f.face.discard()
    expect(f.read().dirty).toBe(false)
  })

  it('retires old directory responses when a reconnect starts a new read', async () => {
    const old = Promise.withResolvers<typeof catalog>()
    onTestFinished(() => { old.resolve(catalog) })
    const f = fixture({ readCatalog: () => old.promise })
    f.readCatalog.mockResolvedValueOnce({ ...catalog, groups: [] })
    f.controller.resetConnection()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    old.resolve(catalog)
    await old.promise
    expect(f.read().rows.main.every(row => !row.available)).toBe(true)
  })

  it('reports a rejected save after leaving and returning to the page', async () => {
    const f = fixture()
    const old = Promise.withResolvers<boolean>()
    onTestFinished(() => { old.resolve(false) })
    f.mutate.mockReturnValueOnce(old.promise)
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.save()
    f.close()
    f.open()
    f.face.editLimit('maxWorkerAttempts', '4')
    old.reject(new Error('late transport failure'))
    await expect(old.promise).rejects.toThrow('late transport failure')
    expect(f.read()).toMatchObject({ failed: true, uncertain: true, saving: false, dirty: true })
    expect(f.read().limits.maxWorkerAttempts).toBe('3')
  })

  it('removes its Host subscription and suppresses directory settlements after disposal', async () => {
    const pending = Promise.withResolvers<typeof catalog>()
    onTestFinished(() => { pending.resolve(catalog) })
    const f = fixture({ readCatalog: () => pending.promise })
    const before = f.read()
    f.controller.dispose()
    expect(f.listenerCount()).toBe(0)
    pending.resolve(catalog)
    await pending.promise
    f.face.editLimit('maxWorkerAttempts', '3')
    f.face.dismissSaved()
    expect(f.read()).toBe(before)
  })

  it('accepts an independently committed identical draft without retaining a conflict', () => {
    const f = fixture()
    f.face.editLimit('maxWorkerAttempts', '3')
    f.update({ ...settings(), maxWorkerAttempts: 3 })
    expect(f.read()).toMatchObject({ dirty: false, conflicted: false, uncertain: false })
    expect(f.read().limits.maxWorkerAttempts).toBe('3')
    f.face.save()
    expect(f.mutate).not.toHaveBeenCalled()
  })

  it('requires a new default for a nonempty pool and chooses one when rebuilding an empty pool', async () => {
    const f = fixture()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    f.face.toggleModel('main', modelKey(main))
    expect(f.read().settings?.main).toEqual({ candidates: [], default: null })
    f.face.toggleModel('main', modelKey(worker))
    expect(f.read().settings?.main.default).toEqual(worker)
    f.face.toggleModel('main', modelKey(main))
    f.face.toggleModel('main', modelKey(worker))
    f.face.selectDefault('main', modelKey(worker))
    expect(f.read().settings?.main.default).toBeNull()
    f.face.toggleModel('main', modelKey(worker))
    expect(f.read().settings?.main.default).toBeNull()
    expect(f.read().errors.main).toBe('defaultRequired')
  })

  it('ignores redundant mode selections and inherited-reviewer pool edits', () => {
    const f = fixture()
    f.face.setReviewerMode('inherit-main')
    f.face.toggleModel('reviewer', modelKey(worker))
    expect(f.read().dirty).toBe(false)
    f.face.setReviewerMode('custom')
    const before = f.read().settings?.reviewer
    f.face.setReviewerMode('custom')
    expect(f.read().settings?.reviewer).toEqual(before)
    f.publish({ writable: false })
    f.face.setReviewerMode('inherit-main')
    expect(f.read().settings?.reviewer).toEqual(before)
  })

  it('does not surface a retired directory rejection over the reconnected directory', async () => {
    const old = Promise.withResolvers<typeof catalog>()
    onTestFinished(() => { old.resolve(catalog) })
    const f = fixture({ readCatalog: () => old.promise })
    f.readCatalog.mockResolvedValueOnce(catalog)
    f.controller.resetConnection()
    await waitForState(f.face, state => state.catalogStatus === 'ready')
    old.reject(new Error('previous connection failed'))
    await expect(old.promise).rejects.toThrow('previous connection failed')
    expect(f.read().catalogStatus).toBe('ready')
    f.controller.dispose()
    f.controller.refreshCatalog()
    expect(f.readCatalog).toHaveBeenCalledTimes(2)
  })
})
